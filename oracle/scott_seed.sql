-- SCOTT 测试用户与示例表(jdbc-proxy 测试用)
-- 由 001-init-scott.sh 在容器首次初始化时以 SYS 身份执行。

CREATE USER scott IDENTIFIED BY tiger QUOTA UNLIMITED ON USERS;
-- Oracle 23ai: CONNECT role no longer implies CREATE SESSION — grant it explicitly
GRANT CREATE SESSION, RESOURCE TO scott;

CREATE TABLE scott.DEPT (
    DEPTNO NUMBER(2)     PRIMARY KEY,
    DNAME  VARCHAR2(14),
    LOC    VARCHAR2(13)
);

CREATE TABLE scott.EMP (
    EMPNO    NUMBER(4)         PRIMARY KEY,
    ENAME    VARCHAR2(10),
    JOB      VARCHAR2(9),
    MGR      NUMBER(4),
    HIREDATE DATE,
    SAL      NUMBER(7,2),
    COMM     NUMBER(7,2),
    DEPTNO   NUMBER(2) REFERENCES scott.DEPT (DEPTNO)
);

CREATE TABLE scott.BONUS (
    ENAME VARCHAR2(10),
    JOB   VARCHAR2(9),
    SAL   NUMBER,
    COMM  NUMBER
);

-- 带自增主键与多种类型的现代测试表(Oracle 23ai IDENTITY)
CREATE TABLE scott.STUDENTS (
    ID     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME   VARCHAR2(50) NOT NULL,
    AGE    NUMBER(3),
    SCORE  NUMBER(5,2),
    BIO    CLOB,
    AVATAR BLOB,
    CREATED TIMESTAMP(6)
);

